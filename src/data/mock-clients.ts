import type { ThemeColor } from '@/constants/theme';

/** Visit workflow state for a client on the seller's route. */
export type VisitStatus =
  | 'no-visitado'
  | 'iniciado'
  | 'trabajado'
  | 'cerrado-observado'
  | 'visitado';

/** Sales channel classification for a client. */
export type SalesChannel = 'horizontal' | 'tradicional' | 'panificacion';

/** Commercial lifecycle state of a client (distinct from the per-visit workflow status). */
export type ClientState = 'closing' | 'gross' | 'recon' | 'discon' | 'nuevo' | 'forgot';

export type MapClient = {
  id: string;
  code: string;
  name: string;
  owner: string;
  route: string;
  address: string;
  phone: string;
  /** Whether this client is scheduled to be visited today. */
  visitToday: boolean;
  status: VisitStatus;
  channel: SalesChannel;
  /** Commercial lifecycle state. */
  clientState: ClientState;
  /** Total pending balance in Bs. */
  balance: number;
  /** Overdue portion of the balance in Bs. */
  overdueDebt: number;
  /** Days remaining before the outstanding balance is due. */
  daysRemaining: number;
  /** Whether the client has an approved credit line. */
  hasCreditLine: boolean;
  /** Approved credit limit in Bs (0 when there is no credit line). */
  creditLimit: number;
  /** Whether the client is a Pareto (top-contribution) account. */
  isPareto: boolean;
  /** How much of the purchase limit has been consumed, 0–100. */
  purchaseLimitPct: number;
  /** Average ticket per order in Bs. */
  avgTicket: number;
  /** Average value delivered per drop in Bs. */
  dropSize: number;
  /** Date of the last purchase, human-formatted. */
  lastPurchase: string;
  lastOrder: string;
  /** Real geo coordinates (Santa Cruz de la Sierra, Bolivia). */
  lat: number;
  lng: number;
};

